/**
 * Metadata factory. A single, typed helper that every page/route uses to
 * produce consistent `<title>`, Open Graph and Twitter cards. Full SEO
 * (sitemap, JSON-LD, RSS, robots) is layered on in Phase 6 — this is the
 * shared foundation those build on.
 */
import type { Metadata } from "next";
import { site, siteUrl } from "@/config/site";

interface BuildMetadataOptions {
  title?: string;
  description?: string;
  /** Path relative to the site root, e.g. `/docs/quickstart`. */
  path?: string;
  /** Absolute or root-relative OG image URL. Defaults to the site OG image. */
  image?: string;
  /** Exclude from indexing (e.g. preview-only routes). */
  noIndex?: boolean;
}

/** Default social share image, generated by the `/og` route. Docs pages
 *  override this with their own per-page image under `/og/docs/*`. */
export const defaultOgImage = "/og";

export function buildMetadata({
  title,
  description = site.description,
  path = "/",
  image = defaultOgImage,
  noIndex = false,
}: BuildMetadataOptions = {}): Metadata {
  const url = new URL(path, siteUrl).toString();
  const resolvedTitle = title
    ? `${title} — ${site.name} Docs`
    : `${site.name} Docs — ${site.tagline}`;
  const ogImage = image.startsWith("http")
    ? image
    : new URL(image, siteUrl).toString();

  return {
    title,
    description,
    alternates: { canonical: url },
    robots: noIndex ? { index: false, follow: false } : undefined,
    openGraph: {
      type: "website",
      siteName: `${site.name} Docs`,
      title: resolvedTitle,
      description,
      url,
      locale: site.locale,
      images: [{ url: ogImage, width: 1200, height: 630, alt: resolvedTitle }],
    },
    twitter: {
      card: "summary_large_image",
      title: resolvedTitle,
      description,
      images: [ogImage],
    },
  };
}
